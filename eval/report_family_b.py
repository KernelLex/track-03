"""Generate docs/RESULTS_FAMILY_B.md from the second pre-registration.

`eval/report.py` and `docs/RESULTS.md` are untouched by this file and stay
published exactly as they were. This is a *power analysis for Claim 1*, run
because the first population could not test the claim the project rests on:
it put n=2 in the administrative subpopulation, and that row swung fifty
points on one case changing.

Everything that governs this run was fixed in
`eval/PREREGISTRATION_FAMILY_B.md`, committed in its own commit before this
file existed, including the threshold at which the claim counts as
unsupported. Re-running after seeing a result is p-hacking; committing the
threshold first is what makes it not.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

from eval.personas.generator import Blocker
from eval.simulate import DEFAULT_TOUCH_COST_PAISE, family_b_only, run_comparison_raw, summarize

OUTPUT_PATH = Path(__file__).resolve().parents[1] / "docs" / "RESULTS_FAMILY_B.md"
PREREGISTRATION = Path(__file__).resolve().parent / "PREREGISTRATION_FAMILY_B.md"

# --- Locked in eval/PREREGISTRATION_FAMILY_B.md, before this file existed ---
N_PERSONAS = 500
SEED = 43
WINDOW_DAYS = 30
PRIMARY_LIFT = 1.0
TOUCH_COST_PAISE = DEFAULT_TOUCH_COST_PAISE

BLOCKER_MIX = {
    Blocker.NONE: 0.30,
    Blocker.INSTRUMENT: 0.20,
    Blocker.ADMINISTRATIVE: 0.35,
    Blocker.DISPUTE: 0.15,
}

CLAIM_1_THRESHOLD_PP = 5.0
"""Percentage points of recovered fraction, Arm C over Arm A, within the
administrative subpopulation. Below this the claim is not supported by this
run -- fixed before the run, because a threshold chosen afterwards is not a
threshold."""


def _preregistration_commit_hash() -> str:
    """Raises on a shallow clone rather than citing the wrong commit.

    Same trap as eval/report.py: with one commit fetched, every file looks
    newly added at HEAD, so git answers with the HEAD sha -- a
    plausible-looking wrong hash, regenerated differently on every push.
    See docs/WHAT_BROKE.md #22."""
    repo_root = OUTPUT_PATH.parent.parent
    shallow = subprocess.run(["git", "rev-parse", "--is-shallow-repository"],
                             capture_output=True, text=True, cwd=repo_root)
    if shallow.stdout.strip() == "true":
        raise SystemExit(
            "This is a shallow clone, so the commit that last touched "
            "eval/PREREGISTRATION_FAMILY_B.md cannot be determined. Run "
            "`git fetch --unshallow` (or check out with fetch-depth: 0) first."
        )
    try:
        out = subprocess.run(
            ["git", "log", "-1", "--format=%H", "--", str(PREREGISTRATION)],
            capture_output=True, text=True, cwd=repo_root, check=True,
        )
        return (out.stdout.strip() or "unknown")[:12]
    except Exception:  # pragma: no cover -- no git at all
        return "unknown"


def _pct(x: float) -> str:
    return f"{x:.1%}"


def _arm_row(name: str, summary) -> str:
    return (f"| {name} | {summary.n} | {_pct(summary.recovered_fraction)} | "
            f"{_pct(summary.resolved_fraction)} | {summary.mean_days_to_resolution:.1f} | "
            f"{_pct(summary.human_escalation_rate)} | {_pct(summary.contact_exhausted_rate)} | "
            f"{summary.mean_touches:.2f} | **{summary.total_bounds_violations}** |")


def build_markdown() -> str:
    personas, outcomes_by_arm = run_comparison_raw(
        n_personas=N_PERSONAS, seed=SEED, window_days=WINDOW_DAYS, lift=PRIMARY_LIFT,
        touch_cost_paise=TOUCH_COST_PAISE, blocker_mix=BLOCKER_MIX,
    )
    whole = {arm: summarize(arm, o) for arm, o in outcomes_by_arm.items()}
    family_b = {arm: summarize(arm, family_b_only(personas, o))
                for arm, o in outcomes_by_arm.items()}

    admin_n = family_b["C"].n
    delta_pp = (family_b["C"].recovered_fraction - family_b["A"].recovered_fraction) * 100
    supported = delta_pp >= CLAIM_1_THRESHOLD_PP

    header = "| Arm | n | Recovered | Resolved | Avg days | Human escalation | Contact-exhausted | Mean touches | **Bounds violations** |\n|---|---|---|---|---|---|---|---|---|"

    verdict = (
        f"**Claim 1 is supported by this run.** Arm C recovers {delta_pp:.1f} percentage points "
        f"more than Arm A within the administrative subpopulation (n={admin_n}), against a "
        f"threshold of {CLAIM_1_THRESHOLD_PP:.0f} points fixed before the run."
        if supported else
        f"**Claim 1 is NOT supported by this run.** Arm C recovers {delta_pp:.1f} percentage "
        f"points more than Arm A within the administrative subpopulation (n={admin_n}), below "
        f"the {CLAIM_1_THRESHOLD_PP:.0f}-point threshold fixed before the run. This result is "
        f"published unchanged, as the pre-registration committed it would be."
    )

    return f"""# Results II — a population built to test Claim 1

Generated by `eval/report_family_b.py` from
[`eval/PREREGISTRATION_FAMILY_B.md`](../eval/PREREGISTRATION_FAMILY_B.md),
committed at `{_preregistration_commit_hash()}` **before this file existed**.
Do not hand-edit — `uv run python eval/report_family_b.py` regenerates it,
and `--check` fails if it drifts.

**This does not replace [`docs/RESULTS.md`](RESULTS.md).** That run and its
pre-registration are untouched and stay published; `eval/report.py` still
regenerates it byte-for-byte. This is a second, separately pre-registered
run — a power analysis for Claim 1, because the first population could not
test it.

## Why this run exists

Claim 1 is that diagnosis-first routing beats reminder-based chasing on
**administrative blockers** — a wrong GSTIN, a PO mismatch, a missing
document — because no amount of reminding fixes a defect in the artifact.

The first population put **n=2** in that subpopulation. Its Family B row
moved from `50.0%` human escalation to `0.0%` when the eval was regenerated
after unrelated fixes: a fifty-point swing from one case changing. A row
that moves that far on one case is not a weak result, it is arithmetically
incapable of being one.

That was a design fault, not bad luck. `generate_population` decided
`true_blocker` downstream of the fitted `p_base`, which is high, so most
invoices self-resolved and only the residual split across the real blocker
types. No seed change fixes that. The blocker mix is therefore **declared**
here, the same way the 12%/8% mandate-defect rates already are.

## Parameters (locked before the run)

| Parameter | Value | Status |
|---|---|---|
| Population size | {N_PERSONAS} | Structural, same as run 1 |
| Seed | {SEED} | Structural — deliberately not 42 |
| Window | {WINDOW_DAYS} days | Inherited, unchanged |
| Touch cost | Rs {TOUCH_COST_PAISE / 100:.0f} | Inherited, unchanged |
| `lift_prior` | {PRIMARY_LIFT} (neutral) | Inherited, unchanged |
| **Blocker mix** | NONE {BLOCKER_MIX[Blocker.NONE]:.0%}, INSTRUMENT {BLOCKER_MIX[Blocker.INSTRUMENT]:.0%}, ADMINISTRATIVE {BLOCKER_MIX[Blocker.ADMINISTRATIVE]:.0%}, DISPUTE {BLOCKER_MIX[Blocker.DISPUTE]:.0%} | **ASSUMED — declared, not fitted** |

## Primary comparison — administrative subpopulation only

n = **{admin_n}** (it was 2).

{header}
{_arm_row("A", family_b["A"])}
{_arm_row("B2", family_b["B2"])}
{_arm_row("C", family_b["C"])}

{verdict}

## Whole population, for context

The constructed mix changes the headline too, and hiding that would be
choosing which number to show. This population is deliberately harder than
the fitted one — 30% self-resolving instead of ~78% — so absolute recovery
is lower across every arm, and that is the point rather than a problem.

{header}
{_arm_row("A", whole["A"])}
{_arm_row("B2", whole["B2"])}
{_arm_row("C", whole["C"])}

## What this run can and cannot say

**It answers a conditional question.** *Given* an administrative blocker,
does the gated diagnosis-first pipeline recover more than reminder-based
chasing? That conditional is what Claim 1 asserts, and the identification
argument (§26.1) is clean: the control arm's action set contains no action
that removes a blocking artifact defect, so the comparison is identified by
the action sets rather than by the response model.

**It cannot say how common administrative blockers are.** The mix is
declared, not measured. Nothing in this repo measures it — and the first
population's mix was not evidence of it either, being a fitted
self-resolution rate applied to a US-derived amount distribution. The
unconditional claim, how much money this saves a real business, needs that
rate measured, and it is not measured here.

**Recovery is still scored against the simulator's own ground truth**, a
modelling convention, not Law 7's rail-confirmed-capture standard. The one
result that meets that standard is n=1 and lives in
[`docs/evidence/REAL_RECOVERY.md`](evidence/REAL_RECOVERY.md).
"""


def main() -> None:
    check_only = "--check" in sys.argv
    markdown = build_markdown()

    if check_only:
        existing = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else None
        if existing != markdown:
            print(f"STALE: {OUTPUT_PATH.name} does not match what eval/report_family_b.py "
                  f"produces. Run 'uv run python eval/report_family_b.py' and commit the result.",
                  file=sys.stderr)
            raise SystemExit(1)
        print(f"{OUTPUT_PATH.name} is current.")
        return

    OUTPUT_PATH.write_text(markdown, encoding="utf-8")
    print(f"Written to {OUTPUT_PATH} ({len(markdown)} chars).")


if __name__ == "__main__":
    main()
